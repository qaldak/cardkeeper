// Smallest valid-looking PNG signature plus padding; enough for signature based detection.
export const PNG_BYTES = Uint8Array.from([
  0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A, 0x00, 0x00, 0x00, 0x0D, 0x49, 0x48, 0x44, 0x52,
])

export const JPEG_BYTES = Uint8Array.from([0xFF, 0xD8, 0xFF, 0xE0, 0x00, 0x10, 0x4A, 0x46, 0x49, 0x46])

export const WEBP_BYTES = Uint8Array.from([
  0x52, 0x49, 0x46, 0x46, 0x24, 0x00, 0x00, 0x00, 0x57, 0x45, 0x42, 0x50, 0x56, 0x50, 0x38, 0x20,
])

export function streamResponse(bytes: Uint8Array, init: ResponseInit = {}): Response {
  return new Response(bytes as BodyInit, { status: 200, ...init })
}
